-- Role helpers ----------------------------------------------------------------------

local ROLE_LABELS = { TANK = "Tank", HEALER = "Healer", DAMAGER = "DPS" }

-- Small role icons from the classic LFG texture (exists on every client).
local ROLE_ICONS = {
    TANK = "|TInterface\\LFGFrame\\UI-LFG-ICON-PORTRAITROLES:14:14:0:0:64:64:0:19:22:41|t",
    HEALER = "|TInterface\\LFGFrame\\UI-LFG-ICON-PORTRAITROLES:14:14:0:0:64:64:20:39:1:20|t",
    DAMAGER = "|TInterface\\LFGFrame\\UI-LFG-ICON-PORTRAITROLES:14:14:0:0:64:64:20:39:22:41|t",
}

function ns.RoleLabel(role)
    return L[ROLE_LABELS[role] or tostring(role)]
end

function ns.RoleIcon(role, size)
    local icon = ROLE_ICONS[role] or ""
    if size then icon = icon:gsub(":14:14:", ":" .. size .. ":" .. size .. ":", 1) end
    return icon
end

-- Roles each class can take (by class only, no spec check).
local CLASS_ROLES = {
    WARRIOR = { TANK = true, DAMAGER = true },
    PALADIN = { TANK = true, HEALER = true, DAMAGER = true },
    HUNTER = { DAMAGER = true },
    ROGUE = { DAMAGER = true },
    PRIEST = { HEALER = true, DAMAGER = true },
    SHAMAN = { HEALER = true, DAMAGER = true },
    MAGE = { DAMAGER = true },
    WARLOCK = { DAMAGER = true },
    DRUID = { TANK = true, HEALER = true, DAMAGER = true },
    DEATHKNIGHT = { TANK = true, DAMAGER = true },
    MONK = { TANK = true, HEALER = true, DAMAGER = true },
    DEMONHUNTER = { TANK = true, DAMAGER = true },
    EVOKER = { HEALER = true, DAMAGER = true },
}

-- Only the roles of the class (no "unusual" shaman / hunter / warlock tank: a group that wants
-- one asks for no tank in its mix). Unknown class: allow everything.
function ns.CanTakeRole(class, role)
    local roles = class and CLASS_ROLES[class]
    if not roles then return true end
    return roles[role] == true
end
